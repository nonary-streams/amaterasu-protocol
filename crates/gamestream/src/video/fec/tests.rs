use super::*;

fn config() -> VideoConfig {
    VideoConfig {
        packet_size: 64,
        fec_percentage: 20,
        min_parity_shards: 2,
        max_fec_blocks: 4,
        encrypted: false,
    }
}

fn frame(data_shards: usize) -> Vec<u8> {
    let mut bytes = vec![0x55; data_shards * 48 - 8];
    bytes[..5].copy_from_slice(&[0, 0, 0, 1, 0x65]);
    bytes
}

fn hevc_idr_access_unit() -> Vec<u8> {
    let mut bytes = Vec::new();
    for (nal_unit_type, payload) in [
        (32_u8, 0x01_u8), // VPS
        (33, 0x02),       // SPS
        (34, 0x03),       // PPS
        (19, 0x80),       // IDR_W_RADL
    ] {
        bytes.extend_from_slice(&[0, 0, 0, 1, nal_unit_type << 1, 1, payload]);
    }
    bytes
}

