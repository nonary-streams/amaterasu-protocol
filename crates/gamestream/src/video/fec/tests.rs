#[test]
fn oversized_or_unrepresentable_fec_never_falls_back_to_no_parity() {
    let mut sender = VideoPacketizer::new(config()).unwrap();
    assert_eq!(
        sender.packetize(&frame(849), false, 1, 0),
        Err(VideoError::TooManyPackets)
    );
    assert_eq!(sender.stream_index, 0);
    let settings = VideoConfig {
        min_parity_shards: 4,
        ..config()
    };
    let mut sender = VideoPacketizer::new(settings).unwrap();
    assert_eq!(
        sender.packetize(&frame(1), false, 1, 0),
        Err(VideoError::InvalidFec)
    );
    assert_eq!(sender.stream_index, 0);
    assert!(matches!(
        VideoPacketizer::new(VideoConfig {
            min_parity_shards: 255,
            ..config()
        }),
        Err(VideoError::InvalidFec)
    ));
    assert!(matches!(
        plan_blocks(
            800,
            VideoConfig {
                packet_size: 65491,
                ..config()
            }
        ),
        Err(VideoError::FecWorkLimit)
    ));
}

fn oracle(mode: &str, data: usize, parity: usize, bytes: usize, input: &[u8]) -> Vec<u8> {
    use std::io::Write;
    use std::process::{Command, Stdio};
    let executable = std::env::var("AMATERASU_NANORS_ORACLE")
        .expect("set AMATERASU_NANORS_ORACLE to the pinned upstream C oracle executable");
    let mut child = Command::new(executable)
        .args([
            mode,
            &data.to_string(),
            &parity.to_string(),
            &bytes.to_string(),
        ])
        .stdin(Stdio::piped())
        .stdout(Stdio::piped())
        .spawn()
        .unwrap();
    child.stdin.take().unwrap().write_all(input).unwrap();
    let output = child.wait_with_output().unwrap();
    assert!(
        output.status.success(),
        "nanors oracle failed: {:?}",
        output.status
    );
    output.stdout
}

#[test]
#[ignore = "requires separately compiled pinned upstream nanors oracle"]
fn upstream_encoder_matches_original_rust_for_multiple_shapes() {
    for (data, parity, bytes) in [
        (1, 2, 13),
        (2, 2, 64),
        (3, 10, 80),
        (64, 13, 1392),
        (212, 43, 80),
        (1, 254, 16),
    ] {
        let mut shards: Vec<Vec<u8>> = (0..data)
            .map(|index| {
                (0..bytes)
                    .map(|offset| ((index * 79 + offset * 13 + offset / 5) & 255) as u8)
                    .collect()
            })
            .collect();
        let expected = oracle("encode", data, parity, bytes, &shards.concat());
        append_parity(&mut shards, parity);
        assert_eq!(
            shards[data..].concat(),
            expected,
            "{data}+{parity} by {bytes}"
        );
    }
}

fn verify_wire_recovery(packets: &[Vec<u8>], erased: &[usize], data: usize, parity: usize) {
    let bytes = packets[0].len();
    let mut input = vec![0; data + parity];
    for index in erased {
        input[*index] = 1;
    }
    for (index, packet) in packets.iter().enumerate() {
        if erased.contains(&index) {
            input.extend(std::iter::repeat_n(0, bytes));
        } else {
            input.extend_from_slice(packet);
        }
    }
    let decoded = oracle("decode", data, parity, bytes, &input);
    for (index, original) in packets[..data].iter().enumerate() {
        let recovered = &decoded[index * bytes..(index + 1) * bytes];
        // Moonlight replaces recovered RTP fields, frameIndex and block bits;
        // fecInfo is not used by its depacketizer. These fields MUST survive RS.
        assert_eq!(
            &recovered[16..20],
            &original[16..20],
            "stream index, erased {erased:?}"
        );
        assert_eq!(
            &recovered[24..27],
            &original[24..27],
            "flags, erased {erased:?}"
        );
        assert_eq!(
            &recovered[32..],
            &original[32..],
            "frame data, erased {erased:?}"
        );
    }
}

#[test]
#[ignore = "requires separately compiled pinned upstream nanors oracle"]
fn upstream_decoder_recovers_wire_packets_with_erasures_and_block_boundaries() {
    // Every two-erasure combination of a 2+2 block, including parity losses.
    let packets = VideoPacketizer::new(config())
        .unwrap()
        .packetize(&frame(2), false, 1, 0)
        .unwrap();
    for first in 0..4 {
        for second in first + 1..4 {
            verify_wire_recovery(&packets, &[first, second], 2, 2);
        }
    }
    for count in [1, 212, 213, 425, 848] {
        let mut sender = VideoPacketizer::new(config()).unwrap();
        sender.stream_index = 0xfffffe;
        let mut original = frame(count);
        original.truncate(original.len() - 3); // Validate zero padding after recovery.
        let packets = sender.packetize(&original, false, 9, u32::MAX).unwrap();
        let mut offset = 0;
        while offset < packets.len() {
            let info = u32::from_le_bytes(packets[offset][28..32].try_into().unwrap());
            let data = (info >> 22) as usize;
            let parity = (data * ((info >> 4) & 255) as usize).div_ceil(100);
            let block = &packets[offset..offset + data + parity];
            verify_wire_recovery(block, &[0], data, parity);
            verify_wire_recovery(block, &[data - 1, data + parity - 1], data, parity);
            verify_wire_recovery(block, &(0..parity).collect::<Vec<_>>(), data, parity);
            offset += data + parity;
        }
    }
}

#[test]
fn negotiated_block_limit_prevents_legacy_multiblock_packets() {
    for invalid in [0, 5, 255] {
        assert!(matches!(
            VideoPacketizer::new(VideoConfig {
                max_fec_blocks: invalid,
                ..config()
            }),
            Err(VideoError::InvalidBlockCount)
        ));
    }
    let mut legacy = VideoPacketizer::new(VideoConfig {
        max_fec_blocks: 1,
        ..config()
    })
    .unwrap();
    let packets = legacy.packetize(&frame(212), false, 1, 0).unwrap();
    assert!(packets.iter().all(|packet| packet[27] == 0));
    let next = legacy.stream_index;
    assert_eq!(
        legacy.packetize(&frame(213), false, 2, 0),
        Err(VideoError::TooManyPackets)
    );
    assert_eq!(legacy.stream_index, next);
}
